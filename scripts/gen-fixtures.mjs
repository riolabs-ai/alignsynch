#!/usr/bin/env node
/**
 * gen-fixtures — bulk quiz generation for the P3 variation gate.
 *
 * `pnpm gen --count 20 --seed 42` writes `data/generated/quizzes.ts`, which is
 * gitignored and validated by `pnpm data:check` when present. The records satisfy the
 * SAME zod schema as the hand-authored fixtures (`content/quiz.ts` zQuiz) — there is
 * no forked validator — and `pnpm gen --count 20 --seed 42 && pnpm data:check` is
 * green, which is the P3 exit criterion.
 *
 * Three properties are load-bearing and tested (`scripts/__tests__/fixture-generator.test.ts`):
 *
 *   1. Reproducible — every value is drawn from a seeded PRNG (mulberry32) over
 *      template pools, and the output is serialized with a fixed key order, so the
 *      same `--seed` and `--count` always produce byte-identical files.
 *   2. Idempotent   — before writing, the generated bytes are compared with the file
 *      on disk; when they match the run reports "unchanged" and writes nothing, so a
 *      re-run without a seed change leaves the files (and their mtime) untouched.
 *   3. Quizzes only — no `promotions.ts` (see "Why there are no generated promotions"),
 *      and a `promotions.ts` an older generator left behind is removed, so the output
 *      directory is always something `pnpm data:check` can pass.
 *   4. Published-record rules — every emitted record is `published` with questions and a
 *      `publishedAt`, and a reward always carries a window. Those are `data:check`'s
 *      W1/W2/W4; the generator refuses to write a set that would report them, so a
 *      regenerated tree cannot undo the fixture repair.
 *
 * Variation dimensions come from TEMPLATES, never from free-form strings:
 *   title pattern  — adjective × topic × format, enumerated and shuffled once
 *   category       — one of the 25 quiz-scope taxonomy ids (content/categories.ts)
 *   difficulty     — `easy | medium | hard` (zDifficulty)
 *   question mix   — count (3–6) and a draw from the per-category + generic banks
 *   image key      — a media registry key, emitted as `media["<key>"].src` (E19-safe)
 *
 * ## Why there are no generated promotions
 *
 * A promotion is keyed `(quizId, slot)`, and its `slot` is a **position a shelf
 * renders**: `data:check` E28 fails when that position renders a different quiz,
 * because the campaign would never run. The shelves in `data/quiz-catalogue.ts` are
 * curation — literal id lists, not a query — so a generated quiz (`quiz-gen-*`) is in
 * none of them, and there is no slot at which one is rendered. A generated promotion
 * is therefore a guaranteed E28 rather than a fixture: the earlier version of this
 * script emitted one per three quizzes (7 at `--count 20 --seed 42`) and turned the
 * documented P3 command red on a tree nobody had broken.
 *
 * The overlay surface is curation, so it stays curated in `data/promotions.ts`. This
 * script removes a `data/generated/promotions.ts` left behind by an older clone, and
 * `data:check` E26 rejects one that reappears — the only slots a campaign may name are
 * the ones the curation map already occupies.
 *
 * Every image key a template names is checked against the on-disk registry (derived
 * from `public/`, the same derivation `scripts/gen-media.mjs` uses) before anything is
 * written, so a stale key fails the generator instead of producing a fixture `data:check`
 * E19 would reject. `data:check` is still the enforcement — this script is only how you
 * (re)generate.
 */
