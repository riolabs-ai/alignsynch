/* ------------------------------------------------------------------ *
 * CLI
 * ------------------------------------------------------------------ */

function parseArgs(argv) {
  const args = { count: 20, seed: 1, out: "data/generated" };
  for (let i = 0; i < argv.length; i += 1) {
    const flag = argv[i];
    const value = argv[i + 1];
    if (flag === "--count") {
      if (!/^\d+$/.test(value ?? "")) fail("--count must be a positive integer", value);
      args.count = Number(value);
      if (args.count < 1) fail("--count must be a positive integer", value);
      i += 1;
    } else if (flag === "--seed") {
      if (!/^\d+$/.test(value ?? "")) fail("--seed must be a non-negative integer", value);
      args.seed = Number(value);
      i += 1;
    } else if (flag === "--out") {
      if (!value || value.startsWith("--")) fail("--out requires a directory path", value);
      args.out = value;
      i += 1;
    } else if (flag === "--help" || flag === "-h") {
      console.log(
        "gen-fixtures: emit bulk quiz fixtures from templates.\n" +
          "  --count <n>   number of quizzes to emit (default 20)\n" +
          "  --seed  <n>   PRNG seed (default 1)\n" +
          "  --out   <dir> output directory (default data/generated)",
      );
      process.exit(0);
    } else {
      fail("unknown argument", flag);
    }
  }
  return args;
}

function fail(problem, got) {
  const shown = got === undefined ? "" : ` (got ${JSON.stringify(got)})`;
  console.error(`gen: ${problem}${shown}`);
  process.exit(1);
}

/* ------------------------------------------------------------------ *
 * Seeded PRNG — mulberry32. Deterministic across runs and platforms.
 * ------------------------------------------------------------------ */

function mulberry32(seed) {
  let a = seed >>> 0;
  return function rng() {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const pick = (rng, arr) => arr[Math.floor(rng() * arr.length)];
const int = (rng, min, max) => min + Math.floor(rng() * (max - min + 1));

/** Fisher–Yates over a copy; `rng` is the only source of randomness. */
function shuffle(rng, arr) {
  const out = [...arr];
  for (let i = out.length - 1; i > 0; i -= 1) {
    const j = Math.floor(rng() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

/* ------------------------------------------------------------------ *
 * Media registry, derived from public/ (same derivation as gen-media.mjs)
 * ------------------------------------------------------------------ */

const PUBLIC = join(process.cwd(), "public");
const IMAGE = /\.(?:png|jpe?g|webp|svg|gif|avif|ico)$/i;
const BY_DIR = {
  avatars: "avatar",
  category: "category-art",
  quiz: "quiz-art",
  news: "news-art",
  tips: "tip-art",
  "how-it-works": "illustration",
};

function kindOf(path) {
  const dir = path.includes("/") ? path.split("/")[0] : undefined;
  if (dir && BY_DIR[dir]) return BY_DIR[dir];
  const name = path.split("/").pop();
  if (/^placeholder(-|\.)/.test(name)) return "fallback";
  if (/-bg\./.test(name)) return "background";
  return "illustration";
}

function walkPublic(dir = PUBLIC, found = []) {
  for (const entry of readdirSync(dir).sort()) {
    if (entry.startsWith(".")) continue;
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) walkPublic(full, found);
    else if (IMAGE.test(entry)) found.push(relative(PUBLIC, full).split("\\").join("/"));
  }
  return found;
}

function registryFromDisk() {
  const registry = new Map();
  for (const file of walkPublic()) {
    const key = file
      .replace(/\.[^.]+$/, "")
      .split("/")
      .join(".");
    registry.set(key, { key, src: `/${file}`, kind: kindOf(file) });
  }
  return registry;
}

