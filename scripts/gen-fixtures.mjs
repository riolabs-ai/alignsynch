const slugify = (text) =>
  text
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");

/** `media["<key>"].src` — the one way an image path is written (E17/E19). */
const mk = (key) => ({ $media: key });

function buildTitlePool() {
  const pool = [];
  for (const category of CATEGORIES) {
    for (const topic of category.topics) {
      for (const adjective of ADJECTIVES) {
        for (const format of FORMATS) {
          pool.push({ title: `${adjective} ${topic} ${format}`, categoryId: category.id, topic });
        }
      }
    }
  }
  return pool;
}

function buildQuestions(rng, category, quizId, count, quizArtKeys) {
  const bank = shuffle(rng, [...category.questions, ...GENERIC_QUESTIONS]);
  const drawn = bank.slice(0, count);
  return drawn.map((question, index) => {
    const id = `${quizId}-q${index + 1}`;
    const options = question.options.map((text, optionIndex) => ({
      id: "abcd"[optionIndex],
      text,
    }));
    const withMedia = {};
    if (quizArtKeys.length > 0 && rng() < 0.3) {
      withMedia.media = {
        src: mk(pick(rng, quizArtKeys)),
        alt: `Question artwork for ${category.id}`,
      };
    }
    return {
      id,
      prompt: question.prompt,
      options,
      correctOptionId: "abcd"[question.answer],
      explanation: question.explanation,
      ...withMedia,
    };
  });
}

function buildStats(rng, index) {
  const plays = int(rng, 100, 5000);
  const capacity = int(rng, plays + 50, plays + 2000);
  const hasBadge = index % 2 === 0;
  const hasReward = index % 4 === 0;
  const stats = {
    isTournament: false,
    recentPlayers: shuffle(rng, PLAYER_NAMES)
      .slice(0, int(rng, 3, 4))
      .map((name) => ({ name })),
    plays,
    capacity,
    rating: int(rng, 35, 50) / 10,
  };
  if (hasBadge) stats.badge = pick(rng, BADGES);
  if (hasReward) {
    stats.rewardCents = pick(rng, REWARD_CENTS);
    stats.limitedTimeEndsAt = pick(rng, LIMITED_TIME_ENDS);
  }
  stats.updatedAt = "2026-10-01T00:00:00.000Z";
  return stats;
}

/**
 * The published-record rules `data:check` reports as W1/W2/W4 on the authored fixtures.
 *
 * A generated record is held to the same three, and the generator is where they are
 * cheapest to enforce: `pnpm gen` fails and writes nothing rather than emitting a set that
 * turns the next `data:check` yellow. The rules live here as well as in the validator
 * because the generator is the only writer of a fixture nobody hand-edits.
 */
function publishedRecordProblems(quizzes) {
  const problems = [];
  for (const quiz of quizzes) {
    if (quiz.status === "published" && quiz.questions.length === 0) {
      problems.push(`[W1] "${quiz.id}" would be published with no questions`);
    }
    if (quiz.status === "published" && quiz.publishedAt === undefined) {
      problems.push(`[W2] "${quiz.id}" would be published with no publishedAt`);
    }
    if (quiz.stats.rewardCents !== undefined && quiz.stats.limitedTimeEndsAt === undefined) {
      problems.push(`[W4] "${quiz.id}" would offer a reward with no limitedTimeEndsAt`);
    }
  }
  return problems;
}

function buildQuiz(rng, template, index, seed, registry) {
  const id = `quiz-gen-${seed}-${index}`;
  const difficulty = pick(rng, DIFFICULTIES);
  const questionCount = int(rng, 3, 6);
  const category = CATEGORIES.find((entry) => entry.id === template.categoryId);
  const coverKey = category.cover;
  const quizArtKeys = [...registry.values()]
    .filter((entry) => entry.kind === "quiz-art")
    .map((entry) => entry.key);
  const authorName = pick(rng, AUTHOR_NAMES);

  return {
    id,
    kind: "quiz",
    slug: `gen-${seed}-${index}-${slugify(template.title)}`,
    title: template.title,
    summary: `Test your knowledge of ${template.topic.toLowerCase()} — ${questionCount} questions, ${difficulty} difficulty.`,
    categoryIds: [template.categoryId],
    tags: [],
    difficulty,
    status: "published",
    publishedAt: "2026-09-01T00:00:00.000Z",
    createdAt: "2026-08-15T00:00:00.000Z",
    questions: buildQuestions(rng, category, id, questionCount, quizArtKeys),
    settings: {
      timeLimitSeconds: pick(rng, [0, 300, 600, 900]),
      questionTimerSeconds: pick(rng, [0, 30, 45, 60]),
      passingScore: pick(rng, [60, 70, 80]),
      shuffleQuestions: index % 2 === 1,
      showExplanations: true,
      allowRetakes: true,
      visibility: "public",
    },
    ...(coverKey === undefined ? {} : { cover: { src: mk(coverKey), alt: template.title } }),
    author: { name: authorName },
    stats: buildStats(rng, index),
  };
}

/* ------------------------------------------------------------------ *
 * Serializer — fixed key order, so output is byte-identical per seed.
 * ------------------------------------------------------------------ */

const isObject = (value) => value !== null && typeof value === "object" && !Array.isArray(value);

function emit(value, depth) {
  if (value === null || value === undefined) return "null";
  if (typeof value === "number" || typeof value === "boolean") return String(value);
  if (typeof value === "string") return JSON.stringify(value);
  if (isObject(value) && "$media" in value) return `media[${JSON.stringify(value.$media)}].src`;
  const pad = "  ".repeat(depth);
  const inner = "  ".repeat(depth + 1);
  if (Array.isArray(value)) {
    if (value.length === 0) return "[]";
    return (
      "[\n" + value.map((item) => `${inner}${emit(item, depth + 1)}`).join(",\n") + `\n${pad}]`
    );
  }
  const keys = Object.keys(value);
  if (keys.length === 0) return "{}";
  return (
    "{\n" +
    keys.map((key) => `${inner}${key}: ${emit(value[key], depth + 1)}`).join(",\n") +
    `\n${pad}}`
  );
}

function emitModule({ header, typeName, importMedia, exportName, records }) {
  const imports = [`import type { ${typeName} } from "../../content/quiz";`];
  if (importMedia) imports.push('import { media } from "../media";');
  const items = records.map((record) => `  ${emit(record, 1)}`).join(",\n");
  return `${header}\n${imports.join("\n")}\n\nexport const ${exportName}: readonly ${typeName}[] = [\n${items}\n];\n`;
}

/* ------------------------------------------------------------------ *
 * Main
 * ------------------------------------------------------------------ */

function main() {
  const args = parseArgs(process.argv.slice(2));

  const registry = registryFromDisk();
  const registryKeys = new Set(registry.keys());

  const missingCovers = CATEGORIES.filter(
    (category) => category.cover !== undefined && !registryKeys.has(category.cover),
  );
  if (missingCovers.length > 0) {
    for (const category of missingCovers) {
      console.error(
        `gen: template cover key ${JSON.stringify(category.cover)} (${category.id}) is not in public/`,
      );
    }
    console.error("gen: fix the template or run `node scripts/gen-media.mjs`; nothing was written");
    process.exit(1);
  }
  const titlePool = buildTitlePool();
  if (args.count > titlePool.length) {
    fail(
      `--count must not exceed the ${titlePool.length} unique titles the templates can produce`,
      args.count,
    );
  }

  const rng = mulberry32(args.seed);
  const titles = shuffle(rng, titlePool).slice(0, args.count);

  const quizzes = titles.map((template, index) =>
    buildQuiz(rng, template, index, args.seed, registry),
  );

  const ruleProblems = publishedRecordProblems(quizzes);
  if (ruleProblems.length > 0) {
    for (const problem of ruleProblems) console.error(`gen: ${problem}`);
    console.error(
      "gen: nothing was written — a generated record is held to the authored fixtures' published-record rules (data:check W1/W2/W4)",
    );
    process.exit(1);
  }

  const outDir = resolve(args.out);
  const seedHeader = `/**
 * Generated by \`pnpm gen --seed ${args.seed} --count ${args.count}\`. Do not hand-edit.
 *
 * This file is gitignored and validated by \`pnpm data:check\` when present. It is a bulk
 * variation of the hand-authored fixtures, emitted from templates by
 * \`scripts/gen-fixtures.mjs\` against the same zod schema (content/quiz.ts). Every image
 * is written as \`media["<key>"].src\` from the media registry (E19).
 */`;

  const quizzesContent = emitModule({
    header: seedHeader,
    typeName: "Quiz",
    importMedia: true,
    exportName: "generatedQuizzes",
    records: quizzes,
  });
  const target = join(outDir, "quizzes.ts");

  // A `promotions.ts` here is a leftover from a generator that emitted campaigns. It
  // cannot be valid (see the header): E28 has no slot that renders a generated quiz, so
  // re-running clears it rather than leaving the gate red for a file this script would
  // never write.
  const stalePromotions = join(outDir, "promotions.ts");
  if (existsSync(stalePromotions)) {
    rmSync(stalePromotions);
    console.log(
      `gen: removed ${stalePromotions} — promotions are curated (data/promotions.ts), never generated: a generated quiz is in no shelf, so E28 has no slot that renders its campaign`,
    );
  }

  let unchanged = false;
  try {
    unchanged = readFileSync(target, "utf8") === quizzesContent;
  } catch {
    unchanged = false;
  }

  if (unchanged) {
    console.log(
      `gen: unchanged — ${outDir} already matches seed=${args.seed} count=${args.count} (no rewrite)`,
    );
    return;
  }

  mkdirSync(outDir, { recursive: true });
  writeFileSync(target, quizzesContent);

  console.log(
    `gen: wrote ${quizzes.length} quizzes to ${outDir} (seed=${args.seed}, count=${args.count})`,
  );
}

main();
