#!/usr/bin/env node
/**
 * gen-brand-icons — the per-brand tab icon, drawn from the brand record (#187 stage 4).
 *
 * The bug this fixes: `app/favicon.ico` is one static file, so both builds shipped the same
 * tab icon and the AlignSynch build showed QuizHub's mark in the browser chrome. The icon is
 * brand data — it is one of the two things a user sees before a single word of the page — so it
 * is recorded per brand (`brand.icon` in `data/brand.ts`) and *drawn from that record* rather
 * than committed as a second copy of a colour.
 *
 * Why generated and not authored: an icon carries a fill, and a hand-drawn one would carry the
 * brand's hex a second time, free to drift from `colors.action`. Here the only authored values
 * are the record's, and the gate re-draws the file and compares (`--check` inside
 * `pnpm data:check`): re-point `colors.action` and the icon is stale until this runs — the same
 * rule `scripts/sample-brand-colors.mjs` applies to the recorded blue and green.
 *
 * The mark is the brand's initial in its action colour on its action ground, which is the only
 * composition that needs no new asset, no font file and no rasteriser: an SVG file, one `<rect>`
 * and one `<text>`, crisp at 16 px and at 512. `public/brand/<id>-icon.svg` is addressed through
 * `data/media.ts` (every `public/` file is, E18) and reached from `app/layout.tsx`'s
 * `metadata.icons` — a component never names a path.
 *
 * Usage:
 *   node --import ./scripts/ts-modules.mjs scripts/gen-brand-icons.mjs           # write
 *   node --import ./scripts/ts-modules.mjs scripts/gen-brand-icons.mjs --check   # gate
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const CHECK = process.argv.includes("--check");

// The record, not a copy of it: `brands` is the table `data/brand.ts` resolves `BRAND` against.
const { brands } = await import("../data/brand.ts");

/** `QuizHub` -> `Q`, `AlignSynch` -> `A`: the initial of the name the record prints. */
function initial(name) {
  const letters = name.replace(/[^A-Za-z]/g, "");
  if (letters.length === 0) throw new Error(`brand name ${JSON.stringify(name)} has no letters`);
  return letters[0].toUpperCase();
}

/**
 * The icon, as SVG. 32×32 is the size a tab asks for; `viewBox` keeps it sharp at any size a
 * browser or a bookmark list scales it to. `width`/`height` are present because
 * `scripts/gen-media.mjs` reads an intrinsic size out of the file's bytes and refuses to guess.
 */
function iconSvg(brand) {
  const letter = initial(brand.name);
  return `<svg xmlns="http://www.w3.org/2000/svg" width="32" height="32" viewBox="0 0 32 32">
  <!-- Generated by scripts/gen-brand-icons.mjs from data/brand.ts — do not edit by hand. -->
  <title>${brand.name}</title>
  <rect width="32" height="32" rx="7" fill="${brand.colors.action}"/>
  <text x="16" y="16.5" text-anchor="middle" dominant-baseline="middle" font-family="Arial, Helvetica, sans-serif" font-size="20" font-weight="700" fill="${brand.colors.actionForeground}">${letter}</text>
</svg>
`;
}

let stale = 0;
for (const [id, brand] of Object.entries(brands)) {
  const path = join(ROOT, "public", "brand", `${id}-icon.svg`);
  const svg = iconSvg(brand);
  if (CHECK) {
    let current = "";
    try {
      current = readFileSync(path, "utf8");
    } catch {
      current = "";
    }
    if (current !== svg) {
      stale++;
      console.error(
        `✗ brand icon: public/brand/${id}-icon.svg is stale (or missing) — ` +
          `run: node --import ./scripts/ts-modules.mjs scripts/gen-brand-icons.mjs`,
      );
    }
    continue;
  }
  writeFileSync(path, svg);
  console.log(`  wrote public/brand/${id}-icon.svg (${brand.name}, ${brand.colors.action})`);
}

if (CHECK) {
  if (stale > 0) process.exit(1);
  console.log(`  ✓ brand icons: ${Object.keys(brands).length} icon(s) match their brand record`);
}
