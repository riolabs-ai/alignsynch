-- 0028_broadcast.sql — the console's one broadcast, and the marks a send leaves (#507, epic #500).
--
-- **Why these three objects.** `news_signup` has collected addresses since #446 and there was no way
-- to use them; `email_event` (0027) records what the provider said happened to a delivery, and the
-- two marks it writes (`news_signup.bounced_at`, `news_signup.complained_at`) are what a send has
-- to read before it mails anybody. A broadcast needs two more facts that no existing row holds:
--
--   *broadcast_send*        one row per send: who pressed it, which segment, how many addresses,
--                          the SHA-256 of the body, and the mode the deployment's mail key was in.
--                          This is the row `admin_action` points at, so the audit entry says
--                          "someone sent a notice to 3 people" without the notice itself, and
--                          `body_hash` is what makes the body auditable without storing it twice.
--
--   *broadcast_recipient*   one row per address per send — the **cooldown's** evidence. The card
--                          asks for a cooldown window per address, and a window is a question about
--                          history ("was this address mailed inside the last 24 hours?"), so the
--                          answer has to be stored. It is the only place an address is written
--                          beside a send, and nothing renders it: the console shows counts.
--
-- *news_signup.unsubscribed_at* — **and this is the one decision worth arguing with 0019.**
-- 0019 says "unsubscribing is a delete of that key, so there is no soft-delete flag to drift", and
-- that sentence was written when nothing read the list. It is wrong for a broadcast in three
-- concrete ways: a deleted row cannot be seeded (#507's acceptance is "seed both, show they are
-- absent"); a deleted row is indistinguishable from an address that was never a signup, so a
-- support read (#506) cannot answer "did this person unsubscribe or did they never join?"; and a
-- hard delete makes "the form says subscribed and the list says no" unrepresentable. The mark is a
-- single nullable instant, written once and cleared when the person submits the footer form again
-- (`lib/news/store.ts`), which is the same "nullable instant, not a boolean" argument 0027 makes
-- for the two bounce marks beside it. Consent is therefore the **absence of all three marks**, and
-- it is one predicate in one place (`lib/db/news-signups.ts`), never a filter over a rendered list.
--
-- **No `gap` column, no `instance` noun**: `db:verify` V2/V16 fail on either name, and this file
-- adds one column and two tables that name neither.
--
-- Idempotent on purpose, like 0001–0027: `db:migrate` ledgers each file in `schema_migrations` and
-- skips what it applied, and a re-run of this file alone is a no-op.

/* ------------------------------------------------------------------ *
 * 1. Consent: the column a broadcast reads
 * ------------------------------------------------------------------ */

-- Nullable, no DEFAULT. "never unsubscribed" and "unsubscribed at 14:02" are the two states, and a
-- default instant would make the first one a lie — 0027's argument for the two marks above.
ALTER TABLE news_signup ADD COLUMN IF NOT EXISTS unsubscribed_at TIMESTAMPTZ;

/* ------------------------------------------------------------------ *
 * 2. The send
 * ------------------------------------------------------------------ */

-- One row per broadcast. `id` is generated by the caller (`lib/admin/broadcast.ts`), not by the
-- table, because it is also the `admin_action.target_id` of the audit row written **after** this
-- insert in the same transaction: `act()` inserts the audit row last, so the id has to exist
-- before the audit row is built. A `DEFAULT gen_random_uuid()` would work only if `act()` could
-- read the generated id back into its target, and it cannot.
CREATE TABLE IF NOT EXISTS broadcast_send (
  id              UUID        PRIMARY KEY,
  -- `user_profile.user_id` of the operator who pressed send. No FK, for 0003's reason: the app does
  -- not constrain the managed auth schema, and a deleted account must not delete the record.
  actor_user_id   TEXT        NOT NULL,
  -- `all` or `since`; the date is a column of its own because "since when" is the question an
  -- operator asks of a past send, and a prose segment would have to be parsed to answer it.
  segment         TEXT        NOT NULL CHECK (segment IN ('all', 'since')),
  segment_since   TIMESTAMPTZ,
  -- The body's SHA-256, lowercase hex. Never the body: the audit row and this row together say
  -- *which* words went out without a second copy of them living in Postgres.
  body_hash       TEXT        NOT NULL CHECK (body_hash ~ '^[0-9a-f]{64}$'),
  -- The subject is metadata, not the body: it is what an operator reads back on the list, and a
  -- hash of it alone would make "which notice was that?" unanswerable from a row.
  subject         TEXT        NOT NULL CHECK (length(btrim(subject)) > 0),
  recipient_count INT         NOT NULL CHECK (recipient_count >= 0),
  -- The deployment's mail key mode at the moment of the send. `live` is a real mailbox; `captured`
  -- is an endpoint override (docs/TWO-PARTY-FLOW.md's capture server), so a send made while
  -- proving the path is distinguishable from one that reached people.
  key_mode        TEXT        NOT NULL CHECK (key_mode IN ('live', 'captured')),
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  -- The segment and its date are one fact: `all` carries no instant, `since` carries one.
  CONSTRAINT broadcast_send_segment_matches_date CHECK (
    (segment = 'all' AND segment_since IS NULL) OR
    (segment = 'since' AND segment_since IS NOT NULL)
  ),
  CONSTRAINT broadcast_send_count_is_bounded CHECK (recipient_count <= 1000)
);

-- "What have we sent lately?" — the list, newest first.
CREATE INDEX IF NOT EXISTS broadcast_send_created_idx ON broadcast_send (created_at DESC);

/* ------------------------------------------------------------------ *
 * 3. The cooldown's evidence
 * ------------------------------------------------------------------ */

-- One row per address per send. The primary key is the pair: an address cannot appear twice in one
-- send, and the constraint is what makes a double-inserted audience a refusal rather than a second
-- row. `ON DELETE CASCADE` because a recipient row is a fact about a send and has no life without
-- it.
CREATE TABLE IF NOT EXISTS broadcast_recipient (
  broadcast_id UUID        NOT NULL REFERENCES broadcast_send (id) ON DELETE CASCADE,
  email        TEXT        NOT NULL,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (broadcast_id, email),
  CONSTRAINT broadcast_recipient_email_is_lowercased CHECK (email = lower(btrim(email))),
  CONSTRAINT broadcast_recipient_email_is_shaped CHECK (email ~ '^[^[:space:]@]+@[^[:space:]@]+$')
);

-- The cooldown's read: "was this address mailed since <window start>?". Written as
-- `(email, created_at DESC)` because the query is an existence test per candidate address inside a
-- window, which is a range scan on this index and a seq scan without it.
CREATE INDEX IF NOT EXISTS broadcast_recipient_email_created_idx
  ON broadcast_recipient (email, created_at DESC);
