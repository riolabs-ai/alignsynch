const byId = new Map(quizCatalogue.map((quiz) => [quiz.id, quiz]));

/** A shelf, resolved to records. Unknown ids cannot survive `data:check` E10. */
export function quizzesFor(shelf: QuizShelf): readonly Quiz[] {
  return quizShelves[shelf].map((id) => {
    const quiz = byId.get(id);
    if (!quiz) throw new Error(`quiz shelf "${shelf}" references unknown quiz "${id}"`);
    return quiz;
  });
}

export function quizById(id: string): Quiz | undefined {
  return byId.get(id);
}
