/**
 * The card catalogue — every quiz the home, explore and category grids show.
 *
 * Before this module the same quizzes were re-authored as card literals in eleven
 * components, with up to five different engagement snapshots for one quiz (D2).
 * They are records now: a card is `selectQuizCard()` / `selectQuizAuthoringCard()`
 * over these, never a literal.
 *
 * Migrated field-for-field from those literals. docs/p1-migration/MIGRATION.md
 * ("D2 — the card grids read the model") records the field mapping, the
 * confirmed conflicts and the values that lost; ledger.json has the per-field
 * diff. Fields the model requires and no fixture carried (summary, difficulty on
 * the marketing cards) are authored here and recorded in the same place.
 */
import type { Quiz, QuizSettings, QuizStats } from "../content/quiz";

/** Authoring knobs these cards all share; only the time limit differs. */
function settings(timeLimitSeconds: number): QuizSettings {
  return {
    timeLimitSeconds,
    questionTimerSeconds: 0,
    passingScore: 70,
    shuffleQuestions: false,
    showExplanations: true,
    allowRetakes: true,
    visibility: "public",
  };
}

/** The defaults the model applies, spelled out so a record is one literal. */
function stats(values: Partial<QuizStats> & { plays: number }): QuizStats {
  return { isTournament: false, recentPlayers: [], ...values };
}

