/**
 * THE RULE IS THE INDEX, NOT THE FILESYSTEM (#1020).
 *
 * `scripts/docs-check.mjs` walked `docs/` and judged every file it found, so the two
 * `AUDIENCE-AND-POSITIONING.md` copies that `.gitignore:73-77` deliberately keeps out of the index
 * failed the gate as orphans *by name* on a tree that was clean at `origin/main` — and did it twice
 * during the v1.19.0 cut. Moving the files out of the checkout was the only way to get a green run,
 * which is not a fix, it is a workaround a human has to remember before every cut.
 *
 * Each case below builds a throwaway git repository in the OS temp dir — `docs/docs.json`, a hub
 * whose region and nav blocks are written by the real `scripts/docs-nav.mjs`, one tracked page — and
 * runs the real check against it. Nothing here touches the checkout's own `docs/`:
 *
 *   1. the fixture is green as committed, so every later failure is the case and not the fixture;
 *   2. a `.md` under `docs/` that `.gitignore` excludes and `git ls-files` does not carry is **not a
 *      page** — no orphan, no manifest failure, exit 0, and the summary counts what it skipped;
 *   3. a **tracked** page dropped from `docs/README.md` still fails with the orphan message, by name
 *      — the case the fix must not widen away;
 *   4. the two together: the excluded file present *and* a tracked page unlisted still fails, so the
 *      skip cannot mask a real orphan;
 *   5. a page removed from `docs/docs.json` still fails — the manifest's own direction is untouched;
 *   6. a root git cannot answer for (a copy with no work tree of its own) keeps every walked file,
 *      because a check that cannot read the index must never silently stop checking.
 */
import { execFileSync, spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { afterEach, describe, expect, it } from "vitest";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const SCRIPT = join(ROOT, "scripts", "docs-check.mjs");
const NAV = join(ROOT, "scripts", "docs-nav.mjs");

/** The page the fixture tracks, and the file it deliberately does not. */
const PAGE = "docs/specs/page.md";
const EXCLUDED = "docs/specs/ignored/AUDIENCE-AND-POSITIONING.md";

/**
 * A child never inherits the caller's `GIT_*` variables: the pre-push hook exports `GIT_DIR` (this
 * checkout is a linked worktree), and an inherited one would point the probe's `git init`/`commit`
 * at the repository being pushed from instead of the throwaway one.
 */
const CHILD_ENV: NodeJS.ProcessEnv = { ...process.env };
for (const key of Object.keys(CHILD_ENV)) {
  if (key.startsWith("GIT_")) delete CHILD_ENV[key];
}

const sandboxes: string[] = [];

afterEach(() => {
  while (sandboxes.length > 0) {
    const dir = sandboxes.pop();
    if (dir) rmSync(dir, { recursive: true, force: true });
  }
});

function write(root: string, path: string, body: string): void {
  mkdirSync(dirname(join(root, path)), { recursive: true });
  writeFileSync(join(root, path), body);
}

function git(root: string, ...args: string[]): string {
  return execFileSync("git", ["-C", root, ...args], {
    encoding: "utf8",
    env: CHILD_ENV,
    stdio: ["ignore", "pipe", "ignore"],
  });
}

function commit(root: string, message: string): void {
  git(root, "add", "--all");
  git(
    root,
    "-c",
    "user.email=probe@example.test",
    "-c",
    "user.name=probe",
    "commit",
    "--quiet",
    "-m",
    message,
  );
}

/**
 * A repository whose docs graph is whole: one section, one tracked page, the hub region and both nav
 * blocks written by the generator the gate itself runs — so a case that fails, fails on its own
 * change and not on a hand-typed approximation of the generated bytes.
 */
function probe(): string {
  const root = mkdtempSync(join(tmpdir(), "docs-check-"));
  sandboxes.push(root);

  write(
    root,
    ".gitignore",
    "# a spec copy that is published elsewhere, kept out of the index\n" + "docs/specs/ignored/\n",
  );
  write(
    root,
    "docs/docs.json",
    `${JSON.stringify(
      {
        sections: [
          {
            id: "specs",
            title: "Specs",
            blurb: "The decisions a build follows.",
            docs: [
              { path: "specs/page.md", title: "Specs page", question: "What does the page say?" },
            ],
          },
        ],
      },
      null,
      2,
    )}\n`,
  );
  write(root, PAGE, "# Specs page\n\nA body the check has no quarrel with.\n");
  write(root, "docs/README.md", "# Docs\n\n<!-- docs-hub:begin -->\n\n<!-- docs-hub:end -->\n");

  const nav = spawnSync(process.execPath, [NAV, "--write", "--root", root], {
    encoding: "utf8",
    env: CHILD_ENV,
  });
  if (nav.status !== 0) throw new Error(`docs-nav --write failed: ${nav.stderr}`);

  git(root, "init", "--quiet");
  commit(root, "fixture: a docs graph that is whole");

  return root;
}

function check(root: string) {
  return spawnSync(process.execPath, [SCRIPT, "--root", root], {
    encoding: "utf8",
    env: CHILD_ENV,
  });
}

/** Every hub row out of the generated region, so a case can drop exactly one. */
function hubText(root: string): string {
  return readFileSync(join(root, "docs/README.md"), "utf8");
}

describe("docs:check and the index", () => {
  it("is green on the fixture as committed", () => {
    const root = probe();
    const run = check(root);

    expect(run.stderr).toBe("");
    expect(run.status).toBe(0);
    expect(run.stdout).toContain("every page is listed once");
    // Nothing was skipped, so the summary says nothing about skips.
    expect(run.stdout).not.toContain("are not in the index");
  });

  it("does not judge a file .gitignore keeps out of the index (#1020)", () => {
    const root = probe();
    write(root, EXCLUDED, "# Audience\n\nA local copy that is never committed.\n");

    // The file exists, is ignored, and the index does not carry it — the whole condition.
    expect(git(root, "status", "--porcelain").trim()).toBe("");
    expect(git(root, "check-ignore", EXCLUDED).trim()).toBe(EXCLUDED);
    expect(() => git(root, "ls-files", "--error-unmatch", EXCLUDED)).toThrow();

    const run = check(root);
    expect(run.stderr).toBe("");
    expect(run.status).toBe(0);
    expect(run.stdout).toContain("1 file(s) under docs/ are not in the index");
  });

  it("still fails a tracked page that the hub does not list, by name", () => {
    const root = probe();
    const before = hubText(root);
    const rows = before.split("\n").filter((line) => !line.includes("[`specs/page.md`]"));
    write(root, "docs/README.md", rows.join("\n"));

    const run = check(root);
    expect(run.status).toBe(1);
    expect(run.stderr).toContain(
      `${PAGE}: not listed in docs/README.md — an orphan page (add it to docs/docs.json)`,
    );
  });

  it("names that orphan even with an excluded file beside it", () => {
    const root = probe();
    write(root, EXCLUDED, "# Audience\n\nA local copy that is never committed.\n");
    const before = hubText(root);
    write(
      root,
      "docs/README.md",
      before
        .split("\n")
        .filter((line) => !line.includes("[`specs/page.md`]"))
        .join("\n"),
    );

    const run = check(root);
    expect(run.status).toBe(1);
    // The skip is not a mute: the tracked page is still named, and the excluded file still is not.
    expect(run.stderr).toContain(`${PAGE}: not listed in docs/README.md — an orphan page`);
    expect(run.stderr).not.toContain(EXCLUDED);
  });

  it("still fails a tracked page that docs/docs.json does not list", () => {
    const root = probe();
    const manifest = JSON.parse(readFileSync(join(root, "docs/docs.json"), "utf8"));
    manifest.sections[0].docs = [];
    write(root, "docs/docs.json", `${JSON.stringify(manifest, null, 2)}\n`);
    commit(root, "fixture: the manifest loses its page");

    const run = check(root);
    expect(run.status).toBe(1);
    // The manifest's own direction is untouched by the skip: the row is gone from `docs.json` and
    // the page is still tracked, so the failure names the path the manifest lost.
    expect(run.stderr).toContain("docs/docs.json: `specs/page.md` is missing");
  });

  it("keeps every walked file when git cannot answer for the root", () => {
    const root = probe();
    // A copy with no work tree of its own: the documented way to demonstrate a rule on a tree.
    const copy = mkdtempSync(join(tmpdir(), "docs-check-copy-"));
    sandboxes.push(copy);
    gitCheckout(root, copy);
    rmSync(join(copy, ".git"), { recursive: true, force: true });
    write(copy, EXCLUDED, "# Audience\n\nA local copy that is never committed.\n");

    const run = check(copy);
    expect(run.status).toBe(1);
    expect(run.stderr).toContain(`${EXCLUDED}: not listed in docs/README.md — an orphan page`);
  });
});

/** Copy the tracked fixture into `to` without its git metadata — a plain tree with the same files. */
function gitCheckout(from: string, to: string): void {
  const files = git(from, "ls-files").split("\n").filter(Boolean);
  for (const file of files) {
    write(to, file, readFileSync(join(from, file), "utf8"));
  }
}
