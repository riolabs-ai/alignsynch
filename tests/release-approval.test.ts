/**
 * `pnpm release:cut --execute` without a TTY — the approval is a committed artifact, and nothing else.
 *
 * The guard this replaces was a terminal: `--execute` refused a non-TTY run and demanded the version
 * typed at the prompt, so a dispatched worker could not tag. That guard is still there for the
 * interactive path. The second door is not a flag and not an environment variable — it is a file a
 * human writes and commits (`docs/releases/<candidate>.approval.json`), judged against the exact
 * commit. Each case below is one of the ways such a file can fail to cover the cut, plus the two
 * properties the mechanism rests on: the artifact is never generated by the script, and the tag step
 * it leads to is `bash scripts/release.sh --tag-only <candidate>` and nothing else.
 *
 * The spawn is asserted from a fake, never run: a suite that tags a release is a suite nobody can
 * re-run. The fixture under `tests/fixtures/` is a shape, not an approval of any release — the real
 * artifact is the owner's act.
 */
import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { afterEach, describe, expect, it } from "vitest";

import {
  approvalBanner,
  approvalPath,
  approvalProblems,
  confirmTypedVersion,
  isBotLogin,
  preApproval,
  readApproval,
  tagOnlyPlan,
} from "../scripts/release-approval.mjs";
import { executeInteractive, executePreApproved } from "../scripts/release-cut.mjs";
import { readApprovalLedger, recordApproval } from "../scripts/release-record.mjs";

const CLI = fileURLToPath(new URL("../scripts/release-cut.mjs", import.meta.url));
const FIXTURE = fileURLToPath(
  new URL("./fixtures/release-approval/1.22.0.approval.json", import.meta.url),
);

const CANDIDATE = "1.22.0";
const FIXTURE_APPROVAL = JSON.parse(readFileSync(FIXTURE, "utf8")) as Record<string, string>;
/** A sha that is on `origin/main` in these cases — the fixture's own, so both sides agree. */
const MAIN_SHA = FIXTURE_APPROVAL.commit;

const roots: string[] = [];

afterEach(() => {
  for (const root of roots.splice(0)) rmSync(root, { recursive: true, force: true });
});

/** A throwaway tree carrying the artifact at the path the cut reads (or nothing, when `null`). */
function tree(artifact: Record<string, unknown> | null = FIXTURE_APPROVAL): string {
  const root = mkdtempSync(join(tmpdir(), "release-approval-"));
  roots.push(root);
  if (artifact !== null) {
    mkdirSync(join(root, "docs", "releases"), { recursive: true });
    writeFileSync(approvalPath(root, CANDIDATE), `${JSON.stringify(artifact, null, 2)}\n`);
  }
  return root;
}

type Run = {
  status: number;
  lines: string[];
  failures: string[];
  spawned: Array<{ command: string; args: string[] }>;
  recorded: Array<Record<string, unknown>>;
};

/** `--execute` with no TTY, with the tag step and the ledger replaced by recorders. */
async function cut(
  root: string,
  overrides: {
    headSha?: string;
    originMainSha?: string;
    status?: string;
    spawnStatus?: number;
  } = {},
): Promise<Run> {
  const lines: string[] = [];
  const failures: string[] = [];
  const spawned: Array<{ command: string; args: string[] }> = [];
  const recorded: Array<Record<string, unknown>> = [];

  const status = await executePreApproved(
    { candidate: CANDIDATE },
    {
      root,
      out: (line?: string) => lines.push(line ?? ""),
      fail: (message: string) => failures.push(message),
      headSha: () => overrides.headSha ?? MAIN_SHA,
      originMainSha: () => overrides.originMainSha ?? MAIN_SHA,
      status: () => overrides.status ?? "",
      spawnTag: (command: string, args: string[]) => {
        spawned.push({ command, args });
        return { status: overrides.spawnStatus ?? 0 };
      },
      recordApproval: (approval: Record<string, unknown>, options: Record<string, unknown>) => {
        recorded.push({ approval, options });
        return join(root, "data", "health", "release-approvals.json");
      },
    },
  );

  return { status, lines, failures, spawned, recorded };
}

const codesOf = (problems: Array<{ code: string }>) => problems.map((problem) => problem.code);
const textOf = (problems: Array<{ message: string }>) =>
  problems.map((problem) => problem.message).join("\n");

describe("without a TTY the cut tags only against a committed approval", () => {
  it("refuses when there is no artifact, and names the path it looked for", async () => {
    const root = tree(null);
    const run = await cut(root);

    expect(run.status).toBe(1);
    expect(run.spawned).toEqual([]);
    expect(run.recorded).toEqual([]);

    const path = approvalPath(root, CANDIDATE);
    expect(path.endsWith(join("docs", "releases", "1.22.0.approval.json"))).toBe(true);
    expect(run.lines.join("\n")).toContain(path);
    expect(run.failures.join("\n")).toContain(path);
  });

  it("refuses an artifact for another version, naming both versions", () => {
    const result = preApproval({
      candidate: CANDIDATE,
      path: approvalPath("/tree", CANDIDATE),
      read: () => ({ ok: true, approval: { ...FIXTURE_APPROVAL, version: "1.23.0" } }),
      headSha: MAIN_SHA,
      originMainSha: MAIN_SHA,
      status: "",
    });

    expect(result.ok).toBe(false);
    expect(codesOf(result.problems)).toContain("version-mismatch");
    const text = textOf(result.problems);
    expect(text).toContain("1.23.0");
    expect(text).toContain("1.22.0");
  });

  it("refuses a commit that is not HEAD, naming both shas", () => {
    const other = "fedcba9876543210fedcba9876543210fedcba98";
    const result = preApproval({
      candidate: CANDIDATE,
      path: approvalPath("/tree", CANDIDATE),
      read: () => ({ ok: true, approval: { ...FIXTURE_APPROVAL, commit: other } }),
      headSha: MAIN_SHA,
      originMainSha: MAIN_SHA,
      status: "",
    });

    expect(result.ok).toBe(false);
    expect(codesOf(result.problems)).toContain("commit-mismatch");
    const text = textOf(result.problems);
    expect(text).toContain(other);
    expect(text).toContain(MAIN_SHA);
  });

  it("refuses an approval for a commit that is on a branch, not on origin/main", () => {
    const branchSha = "1111111111111111111111111111111111111111";
    const result = preApproval({
      candidate: CANDIDATE,
      path: approvalPath("/tree", CANDIDATE),
      read: () => ({ ok: true, approval: { ...FIXTURE_APPROVAL, commit: branchSha } }),
      headSha: branchSha,
      originMainSha: MAIN_SHA,
      status: "",
    });

    expect(result.ok).toBe(false);
    // The artifact names HEAD, so the only failure left is the one that matters: it is not main.
    expect(codesOf(result.problems)).toEqual(["commit-not-on-main"]);
    expect(textOf(result.problems)).toContain(branchSha);
    expect(textOf(result.problems)).toContain(MAIN_SHA);
  });

  it("refuses a dirty tree — the gate checks the tree, so an approval cannot cover dirt", async () => {
    const run = await cut(tree(), { status: " M app/page.tsx\n?? scratch.md\n" });

    expect(run.status).toBe(1);
    expect(run.spawned).toEqual([]);
    expect(run.lines.join("\n")).toContain("tree —");
    expect(run.failures.join("\n")).toContain("tree-dirty");
  });

  it("refuses an approval whose author is a bot, and accepts only a person", () => {
    for (const bot of ["riolabs-ai", "alignsynch", "github-actions[bot]", "dependabot-bot"]) {
      const problems = approvalProblems(
        { ...FIXTURE_APPROVAL, approved_by: bot },
        { candidate: CANDIDATE, headSha: MAIN_SHA, originMainSha: MAIN_SHA, status: "" },
      );
      expect(codesOf(problems)).toContain("approved-by-bot");
      expect(isBotLogin(bot)).toBe(true);
    }

    expect(isBotLogin("jadenblack")).toBe(false);
    expect(
      approvalProblems(
        { ...FIXTURE_APPROVAL, approved_by: "jadenblack" },
        { candidate: CANDIDATE, headSha: MAIN_SHA, originMainSha: MAIN_SHA, status: "" },
      ),
    ).toEqual([]);
  });

  it("refuses a url that is not a comment or issue on this repository", () => {
    for (const url of [
      "https://example.com/approval",
      "https://github.com/someone-else/quizhub/issues/12",
      "https://github.com/riolabs-ai/alignsynch/pull/12/files",
      "  ",
    ]) {
      const problems = approvalProblems(
        { ...FIXTURE_APPROVAL, url },
        { candidate: CANDIDATE, headSha: MAIN_SHA, originMainSha: MAIN_SHA, status: "" },
      );
      expect(codesOf(problems)).toEqual(["url-invalid"]);
    }
  });

  it("proceeds to the tag step on a valid artifact — bash scripts/release.sh --tag-only", async () => {
    const root = tree();
    const run = await cut(root);

    expect(run.status).toBe(0);
    expect(run.failures).toEqual([]);
    expect(run.spawned).toEqual([
      {
        command: "bash",
        args: [join(root, "scripts", "release.sh"), "--tag-only", "1.22.0"],
      },
    ]);
    expect(tagOnlyPlan(root, CANDIDATE)).toMatchObject({ command: "bash" });

    // The banner, as printed: who approved what, and where it is readable.
    const banner = approvalBanner(FIXTURE_APPROVAL);
    expect(banner).toBe(
      `pre-approved by jadenblack at ${FIXTURE_APPROVAL.url} for commit ${MAIN_SHA}`,
    );
    expect(run.lines.join("\n")).toContain(banner);

    // Recorded, not printed only: the ledger row names the tag, the commit and the person.
    expect(run.recorded).toHaveLength(1);
    expect(run.recorded[0].approval).toMatchObject({
      version: "1.22.0",
      commit: MAIN_SHA,
      approved_by: "jadenblack",
      tag: "v1.22.0",
    });
  });

  it("tags nothing when the tag step itself fails", async () => {
    const run = await cut(tree(), { spawnStatus: 2 });

    expect(run.status).toBe(2);
    expect(run.recorded).toEqual([]);
  });

  it("keeps the interactive path: the version is still typed back", async () => {
    const asked: string[] = [];
    const failures: string[] = [];
    const spawned: Array<{ command: string; args: string[] }> = [];

    const refused = await executeInteractive(
      { candidate: CANDIDATE },
      {
        out: () => {},
        fail: (message: string) => failures.push(message),
        ask: async (question: string) => {
          asked.push(question);
          return "";
        },
        spawnTag: (command: string, args: string[]) => {
          spawned.push({ command, args });
          return { status: 0 };
        },
      },
    );

    expect(refused).toBe(1);
    expect(asked.join("\n")).toContain("type the version to tag (v1.22.0)");
    expect(failures.join("\n")).toContain("is not v1.22.0 — nothing was tagged");
    expect(spawned).toEqual([]);

    const accepted = await executeInteractive(
      { candidate: CANDIDATE },
      {
        out: () => {},
        fail: (message: string) => failures.push(message),
        ask: async () => "v1.22.0",
        root: "/tree",
        spawnTag: (command: string, args: string[]) => {
          spawned.push({ command, args });
          return { status: 0 };
        },
      },
    );

    expect(accepted).toBe(0);
    expect(spawned).toHaveLength(1);
    expect(spawned[0].args).toEqual([
      join("/tree", "scripts", "release.sh"),
      "--tag-only",
      "1.22.0",
    ]);
    expect(confirmTypedVersion(" 1.22.0 ", CANDIDATE)).toEqual({ ok: true });
    expect(confirmTypedVersion("1.21.0", CANDIDATE).ok).toBe(false);
  });
});

describe("the artifact is strict, and the script never mints one", () => {
  it("accepts the committed fixture's own shape", () => {
    expect(readApproval(FIXTURE)).toMatchObject({ ok: true });
    expect(FIXTURE_APPROVAL.version).toBe(CANDIDATE);
    expect(
      approvalProblems(FIXTURE_APPROVAL, {
        candidate: CANDIDATE,
        headSha: MAIN_SHA,
        originMainSha: MAIN_SHA,
        status: "",
      }),
    ).toEqual([]);
  });

  it("refuses an unknown key, a missing key and a bad instant by name", () => {
    const root = tree({ ...FIXTURE_APPROVAL, ticket: "1155" });
    const refusal = readApproval(approvalPath(root, CANDIDATE));
    if (refusal.ok) throw new Error("an unknown key must be refused, not read as a comment");
    expect(textOf(refusal.problems)).toContain("unknown key(s) 'ticket'");

    const missing = tree({ version: "1.22.0", commit: MAIN_SHA });
    const short = readApproval(approvalPath(missing, CANDIDATE));
    if (short.ok) throw new Error("a missing key must be refused");
    expect(textOf(short.problems)).toContain("'approved_by'");

    const bad = tree({ ...FIXTURE_APPROVAL, approved_at: "yesterday" });
    const instant = readApproval(approvalPath(bad, CANDIDATE));
    if (!instant.ok) throw new Error(textOf(instant.problems));
    expect(
      codesOf(
        approvalProblems(instant.approval, {
          candidate: CANDIDATE,
          headSha: MAIN_SHA,
          originMainSha: MAIN_SHA,
          status: "",
        }),
      ),
    ).toContain("approved-at-invalid");
  });

  it("offers no flag as an escape hatch", () => {
    const base: NodeJS.ProcessEnv = { ...process.env };
    delete base.HERMES_KANBAN_TASK;

    for (const flag of ["--approved-by", "--approval"]) {
      const run = spawnSync(process.execPath, [CLI, "--execute", flag, "jadenblack"], {
        encoding: "utf8",
        env: base,
      });
      expect(run.status).toBe(2);
      expect(run.stderr).toContain(`unknown argument '${flag}'`);
    }
  });
});

describe("the ledger names which approval covered which tag", () => {
  it("writes one row per version, newest first, and reads it back", () => {
    const root = mkdtempSync(join(tmpdir(), "release-approvals-"));
    roots.push(root);
    const path = join(root, "data", "health", "release-approvals.json");

    expect(readApprovalLedger(path)).toMatchObject({ ok: true, created: true });

    recordApproval(FIXTURE_APPROVAL, { path, recordedAt: "2026-11-17T18:10:00Z" });
    recordApproval(FIXTURE_APPROVAL, { path, recordedAt: "2026-11-17T18:11:00Z" });
    recordApproval({ ...FIXTURE_APPROVAL, version: "1.21.0" }, { path, recordedAt: "x" });

    const ledger = readApprovalLedger(path);
    if (!ledger.ok) throw new Error(ledger.problem);
    expect(ledger.ledger.approvals).toHaveLength(2);
    expect(ledger.ledger.approvals[0]).toMatchObject({
      version: "1.22.0",
      tag: "v1.22.0",
      approved_by: "jadenblack",
      recorded_at: "2026-11-17T18:11:00Z",
    });
    expect(ledger.ledger.approvals[1].version).toBe("1.21.0");
  });
});
